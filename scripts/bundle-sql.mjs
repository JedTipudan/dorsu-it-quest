// Bundles all migrations + seed into supabase/setup.sql — paste it once into
// the Supabase SQL Editor to set up a fresh project. Usage: npm run db:bundle
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const dir = fileURLToPath(new URL('../supabase/', import.meta.url))
const parts = readdirSync(dir + 'migrations').sort().map((f) => `-- >>> migrations/${f}\n` + readFileSync(dir + 'migrations/' + f, 'utf8'))
parts.push('-- >>> seed.sql\n' + readFileSync(dir + 'seed.sql', 'utf8'))
writeFileSync(
  dir + 'setup.sql',
  '-- DOrSU IT Quest — one-shot setup for a NEW Supabase project (GENERATED by scripts/bundle-sql.mjs)\n' +
  '-- Supabase Dashboard → SQL Editor → New query → paste this whole file → Run.\n\n' + parts.join('\n\n'),
)
console.log('supabase/setup.sql written')
