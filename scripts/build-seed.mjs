// Generates supabase/seed.sql from supabase/content/curriculum.mjs
// Usage: npm run db:seed
import { createHash } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { subjects, badges } from '../supabase/content/curriculum.mjs'

const out = fileURLToPath(new URL('../supabase/seed.sql', import.meta.url))

// Deterministic UUID from a key, so re-running the seed is idempotent.
const uuid = (key) => {
  const h = createHash('md5').update(`dorsu-it-quest:${key}`).digest('hex')
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`
}
const shortId = (key) => 'o' + createHash('md5').update(`opt:${key}`).digest('hex').slice(0, 6)

// Deterministic shuffle (so options/ids never reveal the answer)
const seededShuffle = (arr, seed) => {
  const a = [...arr]
  let s = parseInt(createHash('md5').update(seed).digest('hex').slice(0, 8), 16)
  const rand = () => ((s = (s * 1664525 + 1013904223) >>> 0) / 2 ** 32)
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

const lit = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const json = (v) => `${lit(JSON.stringify(v))}::jsonb`

function buildQuestion(q, key) {
  const d = q.d ?? 1
  const base = { prompt: q.prompt, code: q.code ?? null, topic: q.topic ?? null, difficulty: d, points: q.points ?? 10 * d }
  switch (q.kind) {
    case 'mcq':
    case 'multi': {
      const opts = q.options.map((t, i) => ({ id: shortId(`${key}:${i}`), text: t.replace(/^\*/, ''), correct: t.startsWith('*') }))
      const shuffled = seededShuffle(opts, key)
      const options = shuffled.map(({ id, text }) => ({ id, text }))
      const answer = q.kind === 'mcq'
        ? { value: opts.find((o) => o.correct).id }
        : { values: opts.filter((o) => o.correct).map((o) => o.id) }
      return { ...base, kind: q.kind, options, answer }
    }
    case 'truefalse':
      return { ...base, kind: 'truefalse', options: [{ id: 'true', text: 'True' }, { id: 'false', text: 'False' }], answer: { value: String(q.value) } }
    case 'order': {
      const items = q.items.map((t, i) => ({ id: shortId(`${key}:${i}`), text: t }))
      let shuffled = seededShuffle(items, key)
      if (shuffled.every((o, i) => o.id === items[i].id)) shuffled = [...items].reverse()
      return { ...base, kind: 'order', options: shuffled, answer: { order: items.map((o) => o.id) } }
    }
    case 'short':
    case 'code':
      return { ...base, kind: q.kind, options: [], answer: { accepted: q.accepted } }
    default:
      throw new Error(`Unknown kind ${q.kind}`)
  }
}

const lines = []
const push = (s) => lines.push(s)
push('-- =====================================================================')
push('-- DOrSU IT Quest — seed data (GENERATED by scripts/build-seed.mjs)')
push('-- Do not edit by hand; edit supabase/content/curriculum.mjs instead.')
push('-- Safe to run more than once.')
push('-- =====================================================================')
push('begin;')

let qCount = 0
const questRows = []
const questionRows = []
const keyRows = []

subjects.forEach((s, si) => {
  const sid = uuid(`subject:${s.slug}`)
  push(`insert into public.subjects (id, slug, name, short_name, description, icon, color, sort_order) values (${lit(sid)}, ${lit(s.slug)}, ${lit(s.name)}, ${lit(s.short_name)}, ${lit(s.description)}, ${lit(s.icon)}, ${lit(s.color)}, ${si + 1}) on conflict (slug) do update set name = excluded.name, short_name = excluded.short_name, description = excluded.description, icon = excluded.icon, color = excluded.color, sort_order = excluded.sort_order;`)

  const quests = [
    ...s.quests.map((q, i) => ({ ...q, sort: i + 1, published: true })),
    { key: `${s.slug}-pretest`, title: `${s.name} Pretest`, type: 'pretest', difficulty: 2, xp: 0, time: 900, sort: 100, published: true,
      description: `Baseline assessment for ${s.name}. Take it once before you start the quests. No feedback is shown so the results stay valid.`, questions: s.pretest },
    { key: `${s.slug}-posttest`, title: `${s.name} Posttest`, type: 'posttest', difficulty: 2, xp: 0, time: 900, sort: 101, published: false,
      description: `Final assessment for ${s.name}. Your instructor opens this at the end of the review period.`, questions: s.pretest },
  ]

  for (const q of quests) {
    const qid = uuid(`quest:${q.key}`)
    questRows.push(`(${lit(qid)}, ${lit(sid)}, ${lit(q.title)}, ${lit(q.description)}, ${lit(q.type)}, ${q.difficulty}, ${q.xp}, ${q.time ?? 'null'}, ${q.sort}, ${q.published})`)
    q.questions.forEach((raw, i) => {
      const key = `${q.key}:${i}`
      const built = buildQuestion(raw, key)
      const id = uuid(`question:${key}`)
      questionRows.push(`(${lit(id)}, ${lit(qid)}, ${lit(built.kind)}, ${lit(built.prompt)}, ${lit(built.code)}, ${json(built.options)}, ${lit(built.topic)}, ${built.difficulty}, ${built.points}, ${i + 1})`)
      keyRows.push(`(${lit(id)}, ${json(built.answer)}, ${lit(raw.explanation ?? '')})`)
      qCount++
    })
  }
})

push('')
push('insert into public.quests (id, subject_id, title, description, type, difficulty, xp_reward, time_limit_seconds, sort_order, is_published) values')
push(questRows.join(',\n') + '\non conflict (id) do update set title = excluded.title, description = excluded.description, type = excluded.type, difficulty = excluded.difficulty, xp_reward = excluded.xp_reward, time_limit_seconds = excluded.time_limit_seconds, sort_order = excluded.sort_order;')
push('')
push('insert into public.questions (id, quest_id, kind, prompt, code, options, topic, difficulty, points, sort_order) values')
push(questionRows.join(',\n') + '\non conflict (id) do update set kind = excluded.kind, prompt = excluded.prompt, code = excluded.code, options = excluded.options, topic = excluded.topic, difficulty = excluded.difficulty, points = excluded.points, sort_order = excluded.sort_order;')
push('')
push('insert into public.question_keys (question_id, answer, explanation) values')
push(keyRows.join(',\n') + '\non conflict (question_id) do update set answer = excluded.answer, explanation = excluded.explanation;')
push('')

const badgeRows = badges.map((b, i) =>
  `(${lit(uuid(`badge:${b.code}`))}, ${lit(b.code)}, ${lit(b.name)}, ${lit(b.description)}, ${lit(b.icon)}, ${lit(b.tier)}, ${lit(b.rule_type)}, ${b.rule_value ?? 1}, ${b.subject ? lit(uuid(`subject:${b.subject}`)) : 'null'}, ${i + 1})`)
push('insert into public.badges (id, code, name, description, icon, tier, rule_type, rule_value, subject_id, sort_order) values')
push(badgeRows.join(',\n') + '\non conflict (code) do update set name = excluded.name, description = excluded.description, icon = excluded.icon, tier = excluded.tier, rule_type = excluded.rule_type, rule_value = excluded.rule_value, subject_id = excluded.subject_id, sort_order = excluded.sort_order;')
push('')
push('commit;')

writeFileSync(out, lines.join('\n') + '\n')
console.log(`seed.sql written: ${subjects.length} subjects, ${questRows.length} quests, ${qCount} questions, ${badges.length} badges`)
